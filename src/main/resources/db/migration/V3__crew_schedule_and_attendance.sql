-- 크루 일정, 동승자 기본 탈 곳·내릴 곳, 출석
-- 차량 앱 "오늘의 카풀" 화면과 운행 시작의 riders를 서버 데이터로 채우기 위한 것
-- 모두 기본값이라 운행은 여전히 그날 정한 출발지, 목적지, 탈 곳으로 시작함 (출퇴근으로 고정하지 않음)

alter table crews
    add column departure_time       time,
    add column departure_days       integer not null default 0,
    add column origin_place_id      bigint,
    add column destination_place_id bigint,
    add constraint ck_crews_departure_days check (departure_days between 0 and 127),
    add constraint fk_crews_origin_place foreign key (origin_place_id) references crew_places (id),
    add constraint fk_crews_destination_place foreign key (destination_place_id) references crew_places (id);

alter table crew_members
    add column board_place_id  bigint,
    add column alight_place_id bigint,
    add constraint fk_crew_members_board_place foreign key (board_place_id) references crew_places (id),
    add constraint fk_crew_members_alight_place foreign key (alight_place_id) references crew_places (id);

-- 기본은 "탐". 안 타는 날이나 그날만 다른 곳에서 타는 날만 행이 생김
create table crew_attendances (
    id             bigint generated by default as identity primary key,
    crew_member_id bigint                      not null,
    service_date   date                        not null,
    attending      boolean                     not null,
    board_place_id bigint,
    updated_at     timestamp(6) with time zone not null,
    constraint uk_crew_attendances_member_date unique (crew_member_id, service_date),
    constraint fk_crew_attendances_crew_member foreign key (crew_member_id) references crew_members (id),
    constraint fk_crew_attendances_board_place foreign key (board_place_id) references crew_places (id)
);
