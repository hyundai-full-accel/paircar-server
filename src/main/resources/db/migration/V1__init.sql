-- 페어카 크루 서버 초기 스키마 (docs/schema.dbml 기준)
-- 시각은 모두 timestamptz(UTC 저장), 운행일과 정산 월은 date(KST 기준)
-- Enum은 varchar + check 제약으로 저장 (JPA @Enumerated(STRING))

-- ---------- member ----------

create table members (
    id         bigint generated by default as identity primary key,
    nickname   varchar(30)                 not null,
    created_at timestamp(6) with time zone not null
);

create table member_bank_accounts (
    id             bigint generated by default as identity primary key,
    member_id      bigint                      not null,
    bank_name      varchar(30)                 not null,
    account_number varchar(30)                 not null,
    account_holder varchar(30)                 not null,
    created_at     timestamp(6) with time zone not null,
    updated_at     timestamp(6) with time zone not null,
    constraint uk_member_bank_accounts_member unique (member_id),
    constraint fk_member_bank_accounts_member foreign key (member_id) references members (id)
);

create table member_tokens (
    id         bigint generated by default as identity primary key,
    member_id  bigint                      not null,
    token_hash varchar(64)                 not null,
    expires_at timestamp(6) with time zone not null,
    revoked_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    constraint uk_member_tokens_token_hash unique (token_hash),
    constraint fk_member_tokens_member foreign key (member_id) references members (id)
);
create index idx_member_tokens_member_id on member_tokens (member_id);

-- ---------- car ----------

create table cars (
    id                  bigint generated by default as identity primary key,
    vehicle_key         varchar(64)                 not null,
    fuel_type           varchar(20)                 not null,
    manual_fuel_economy numeric(5, 2),
    created_at          timestamp(6) with time zone not null,
    constraint uk_cars_vehicle_key unique (vehicle_key),
    constraint ck_cars_fuel_type check (fuel_type in ('GASOLINE', 'DIESEL', 'LPG', 'HYBRID', 'EV'))
);

create table member_cars (
    id         bigint generated by default as identity primary key,
    member_id  bigint                      not null,
    car_id     bigint                      not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_member_cars_member_car unique (member_id, car_id),
    constraint fk_member_cars_member foreign key (member_id) references members (id),
    constraint fk_member_cars_car foreign key (car_id) references cars (id)
);

-- ---------- crew ----------

create table crews (
    id                    bigint generated by default as identity primary key,
    name                  varchar(50)                 not null,
    settlement_mode       varchar(20)                 not null default 'FAIR',
    include_driver        boolean                     not null default true,
    monthly_fixed_won     integer,
    manual_fuel_price_won integer,
    created_at            timestamp(6) with time zone not null,
    constraint ck_crews_settlement_mode check (settlement_mode in ('FAIR', 'EQUAL', 'FIXED_MONTHLY'))
);

create table crew_members (
    id        bigint generated by default as identity primary key,
    crew_id   bigint                      not null,
    member_id bigint                      not null,
    joined_at timestamp(6) with time zone not null,
    constraint uk_crew_members_crew_member unique (crew_id, member_id),
    constraint fk_crew_members_crew foreign key (crew_id) references crews (id),
    constraint fk_crew_members_member foreign key (member_id) references members (id)
);
create index idx_crew_members_member_id on crew_members (member_id); -- 내 크루 목록

create table crew_invites (
    id         bigint generated by default as identity primary key,
    crew_id    bigint                      not null,
    code       varchar(32)                 not null,
    expires_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_crew_invites_code unique (code),
    constraint fk_crew_invites_crew foreign key (crew_id) references crews (id)
);
create index idx_crew_invites_crew_id on crew_invites (crew_id);

create table crew_places (
    id         bigint generated by default as identity primary key,
    crew_id    bigint                      not null,
    name       varchar(50)                 not null,
    latitude   numeric(9, 6)               not null,
    longitude  numeric(9, 6)               not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_crew_places_crew_name unique (crew_id, name),
    constraint fk_crew_places_crew foreign key (crew_id) references crews (id)
);

create table crew_member_detours (
    id                     bigint generated by default as identity primary key,
    passenger_id           bigint                      not null,
    driver_id              bigint                      not null,
    place_id               bigint                      not null,
    detour_km              numeric(6, 1)               not null,
    driver_confirmed_at    timestamp(6) with time zone,
    passenger_confirmed_at timestamp(6) with time zone,
    created_at             timestamp(6) with time zone not null,
    updated_at             timestamp(6) with time zone not null,
    constraint uk_crew_member_detours_passenger_driver_place unique (passenger_id, driver_id, place_id),
    constraint ck_crew_member_detours_parties check (passenger_id <> driver_id),
    constraint fk_crew_member_detours_passenger foreign key (passenger_id) references crew_members (id),
    constraint fk_crew_member_detours_driver foreign key (driver_id) references crew_members (id),
    constraint fk_crew_member_detours_place foreign key (place_id) references crew_places (id)
);

-- ---------- trip ----------

create table trips (
    id                   bigint generated by default as identity primary key,
    driver_id            bigint                      not null,
    car_id               bigint                      not null,
    origin_place_id      bigint                      not null,
    destination_place_id bigint                      not null,
    service_date         date                        not null,
    started_at           timestamp(6) with time zone not null,
    ended_at             timestamp(6) with time zone,
    start_odometer_km    numeric(9, 1)               not null,
    end_odometer_km      numeric(9, 1),
    toll_fare_won        integer                     not null default 0,
    route_polyline       text,
    constraint fk_trips_driver foreign key (driver_id) references crew_members (id),
    constraint fk_trips_car foreign key (car_id) references cars (id),
    constraint fk_trips_origin_place foreign key (origin_place_id) references crew_places (id),
    constraint fk_trips_destination_place foreign key (destination_place_id) references crew_places (id)
);
create index idx_trips_driver_service_date on trips (driver_id, service_date);

create table boardings (
    id                 bigint generated by default as identity primary key,
    trip_id            bigint                      not null,
    crew_member_id     bigint                      not null,
    board_place_id     bigint                      not null,
    alight_place_id    bigint                      not null,
    boarded_at         timestamp(6) with time zone,
    board_odometer_km  numeric(9, 1),
    alighted_at        timestamp(6) with time zone,
    alight_odometer_km numeric(9, 1),
    constraint uk_boardings_trip_crew_member unique (trip_id, crew_member_id),
    constraint fk_boardings_trip foreign key (trip_id) references trips (id),
    constraint fk_boardings_crew_member foreign key (crew_member_id) references crew_members (id),
    constraint fk_boardings_board_place foreign key (board_place_id) references crew_places (id),
    constraint fk_boardings_alight_place foreign key (alight_place_id) references crew_places (id)
);
create index idx_boardings_crew_member_id on boardings (crew_member_id);

create table trip_segments (
    id                  bigint generated by default as identity primary key,
    trip_id             bigint        not null,
    seq                 smallint      not null,
    start_odometer_km   numeric(9, 1) not null,
    end_odometer_km     numeric(9, 1) not null,
    fuel_economy        numeric(5, 2) not null,
    fuel_economy_source varchar(20)   not null,
    start_point_index   integer,
    end_point_index     integer,
    constraint uk_trip_segments_trip_seq unique (trip_id, seq),
    constraint ck_trip_segments_fuel_economy_source check (fuel_economy_source in ('MEASURED', 'MANUAL')),
    constraint fk_trip_segments_trip foreign key (trip_id) references trips (id)
);

create table trip_segment_riders (
    id              bigint generated by default as identity primary key,
    trip_segment_id bigint not null,
    boarding_id     bigint not null,
    constraint uk_trip_segment_riders_segment_boarding unique (trip_segment_id, boarding_id),
    constraint fk_trip_segment_riders_segment foreign key (trip_segment_id) references trip_segments (id),
    constraint fk_trip_segment_riders_boarding foreign key (boarding_id) references boardings (id)
);
create index idx_trip_segment_riders_boarding_id on trip_segment_riders (boarding_id);

-- ---------- settlement ----------

create table fuel_prices (
    id           bigint generated by default as identity primary key,
    fuel_type    varchar(20)                 not null,
    month        date                        not null,
    price_won    integer                     not null,
    collected_at timestamp(6) with time zone not null,
    constraint uk_fuel_prices_fuel_type_month unique (fuel_type, month),
    constraint ck_fuel_prices_fuel_type check (fuel_type in ('GASOLINE', 'DIESEL', 'LPG', 'HYBRID', 'EV'))
);

create table receipts (
    id                   bigint generated by default as identity primary key,
    payer_id             bigint                      not null,
    payee_id             bigint                      not null,
    month                date                        not null,
    settlement_mode      varchar(20)                 not null,
    fuel_economy         numeric(5, 2)               not null,
    fuel_economy_source  varchar(20)                 not null,
    fuel_price_won       integer                     not null,
    amount_won           integer                     not null,
    payee_bank_name      varchar(30)                 not null,
    payee_account_number varchar(30)                 not null,
    payee_account_holder varchar(30)                 not null,
    waived_at            timestamp(6) with time zone,
    issued_at            timestamp(6) with time zone not null,
    constraint uk_receipts_payer_payee_month unique (payer_id, payee_id, month),
    constraint ck_receipts_parties check (payer_id <> payee_id),
    constraint ck_receipts_settlement_mode check (settlement_mode in ('FAIR', 'EQUAL', 'FIXED_MONTHLY')),
    constraint ck_receipts_fuel_economy_source check (fuel_economy_source in ('MEASURED', 'MANUAL')),
    constraint fk_receipts_payer foreign key (payer_id) references crew_members (id),
    constraint fk_receipts_payee foreign key (payee_id) references crew_members (id)
);
create index idx_receipts_payee_month on receipts (payee_id, month);

create table receipt_items (
    id                 bigint generated by default as identity primary key,
    receipt_id         bigint         not null,
    boarding_id        bigint         not null,
    shared_distance_km numeric(8, 1)  not null,
    shared_cost_won    numeric(10, 2) not null,
    detour_km          numeric(6, 1)  not null,
    detour_cost_won    numeric(10, 2) not null,
    toll_won           numeric(10, 2) not null,
    constraint uk_receipt_items_boarding unique (boarding_id),
    constraint fk_receipt_items_receipt foreign key (receipt_id) references receipts (id),
    constraint fk_receipt_items_boarding foreign key (boarding_id) references boardings (id)
);
create index idx_receipt_items_receipt_id on receipt_items (receipt_id);

-- ---------- live ----------

create table push_subscriptions (
    id         bigint generated by default as identity primary key,
    member_id  bigint                      not null,
    endpoint   varchar(1024)               not null,
    p256dh     varchar(255)                not null,
    auth       varchar(255)                not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint uk_push_subscriptions_endpoint unique (endpoint),
    constraint fk_push_subscriptions_member foreign key (member_id) references members (id)
);
create index idx_push_subscriptions_member_id on push_subscriptions (member_id);
