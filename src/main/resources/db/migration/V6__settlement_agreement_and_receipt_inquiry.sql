-- 정산 기준 동의, 영수증 기록 확인 요청 (동승자 웹 시안, 차량 앱 P3 요청)

-- 정산 방식(나누는 방법, 운전자 포함)이 마지막으로 바뀐 시각. 이보다 먼저 한 동의는 다시 받아야 함
alter table crews
    add column settlement_changed_at timestamp(6) with time zone;

-- 크루 멤버가 정산 기준에 동의한 시각 (참여할 때, 기준이 바뀐 뒤 다시)
alter table crew_members
    add column settlement_agreed_at timestamp(6) with time zone;

-- 영수증 기록 확인 요청. 영수증은 바꾸지 않고, 내는 사람이 받는 사람(운전자)에게 확인을 요청함
create table receipt_inquiries (
    id           bigint generated by default as identity primary key,
    receipt_id   bigint                      not null,
    requester_id bigint                      not null,
    message      varchar(500)                not null,
    created_at   timestamp(6) with time zone not null,
    resolved_at  timestamp(6) with time zone,
    constraint fk_receipt_inquiries_receipt foreign key (receipt_id) references receipts (id),
    constraint fk_receipt_inquiries_requester foreign key (requester_id) references crew_members (id)
);

create index idx_receipt_inquiries_receipt_id on receipt_inquiries (receipt_id);
